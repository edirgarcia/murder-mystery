class ProjectCategory(str, Enum):
    CITY = "city"
    MARKET = "market"
    PRESTIGE = "prestige"


class MarketAxis(str, Enum):
    SUPPLY = "supply"
    DEMAND = "demand"


class MarketLevel(str, Enum):
    DOWN = "down"
    NEUTRAL = "neutral"
    UP = "up"


class EffectKind(str, Enum):
    NONE = "none"
    PRODUCTION = "production"  # +amount production of resource
    INCOME = "income"  # +amount cash at Round Start
    UPKEEP_REDUCTION = "upkeep_reduction"  # -amount upkeep of resource
    STORAGE = "storage"  # +amount storage capacity
    MARKET = "market"  # sets the global axis/level slot for resource


@dataclass(frozen=True)
class Effect:
    kind: EffectKind = EffectKind.NONE
    resource: Resource | None = None
    amount: int = 0
    axis: MarketAxis | None = None
    level: MarketLevel | None = None

    def describe(self) -> str:
        res = self.resource.value.title() if self.resource else ""
        match self.kind:
            case EffectKind.PRODUCTION:
                return f"+{self.amount} {res} production each round"
            case EffectKind.INCOME:
                return f"+${self.amount} income each round"
            case EffectKind.UPKEEP_REDUCTION:
                return f"-{self.amount} {res} upkeep"
            case EffectKind.STORAGE:
                return f"+{self.amount} storage"
            case EffectKind.MARKET:
                return f"{res} {self.axis.value.title()} {self.level.value.title()} (global)"
        return ""


@dataclass(frozen=True)
class ProjectCard:
    id: str
    name: str
    category: ProjectCategory
    cost: dict[Resource, int]
    effect: Effect = Effect()
    vp: int = 0
    tier: str | None = None  # prestige only: "small" | "medium" | "major"

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "name": self.name,
            "category": self.category.value,
            "cost": {r.value: n for r, n in self.cost.items()},
            "effect": self.effect.describe(),
            "effect_kind": self.effect.kind.value,
            "vp": self.vp,
            "tier": self.tier,
        }


