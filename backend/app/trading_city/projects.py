# --- Generated ingredients (balanced demand, optional basic -> refined arc) ---

BASIC: tuple[Resource, ...] = RESOURCES[:4]  # Grain, Livestock, Timber, Iron
REFINED: tuple[Resource, ...] = RESOURCES[4:]  # Cloth, Tools, Wine, Spices

# Share of each card group's units that are basic goods (the rest are refined).
# Within each half, all four resources get an equal share. Market cards are
# always rotationally symmetric (50/50) and not affected.
RESOURCE_SPLITS: dict[str, dict[str, float] | None] = {
    "handwritten": None,  # the original hand-picked ingredients (uneven: Timber/Iron heavy)
    "even": {"city": 0.5, "grand": 0.5, "small": 0.5, "medium": 0.5, "major": 0.5},
    "gentle": {"city": 0.65, "grand": 0.5, "small": 0.65, "medium": 0.5, "major": 0.35},
    "strong": {"city": 0.75, "grand": 0.5, "small": 0.75, "medium": 0.5, "major": 0.2},
}


def _targets(units: int, basic_share: float) -> dict[Resource, float]:
    per_basic = units * basic_share / len(BASIC)
    per_refined = units * (1 - basic_share) / len(REFINED)
    return {r: per_basic if r in BASIC else per_refined for r in RESOURCES}


def _pick(deficit: dict[Resource, float], exclude: set[Resource], card_index: int) -> Resource:
    """Resource with the biggest remaining deficit; ties rotate by card so cards differ."""
    n = len(RESOURCES)
    return max(
        (r for r in RESOURCES if r not in exclude),
        key=lambda r: (round(deficit[r], 6), -((RESOURCES.index(r) - card_index) % n)),
    )


def _fill(cards: tuple[ProjectCard, ...], basic_share: float) -> tuple[ProjectCard, ...]:
    """Re-assign each card's ingredients, keeping its shape, to hit the target split."""
    total = sum(sum(c.cost.values()) for c in cards)
    target = _targets(total, basic_share)
    assigned: Counter[Resource] = Counter()
    result = []
    for i, card in enumerate(cards):
        cost: dict[Resource, int] = {}
        for amount in sorted(card.cost.values(), reverse=True):
            deficit = {r: target[r] - assigned[r] for r in RESOURCES}
            r = _pick(deficit, set(cost), i)
            cost[r] = amount
            assigned[r] += amount
        result.append(replace(card, cost=cost))
    return tuple(result)


def _grand_from(plain: tuple[ProjectCard, ...], basic_share: float) -> tuple[ProjectCard, ...]:
    """Grand variants: the plain cost plus 1 each of two new resources, steered to the split."""
    total = sum(sum(c.cost.values()) + 2 for c in plain)
    target = _targets(total, basic_share)
    assigned: Counter[Resource] = Counter()
    for c in plain:
        assigned.update(c.cost)
    result = []
    for i, card in enumerate(plain):
        cost = dict(card.cost)
        for _ in range(2):
            deficit = {r: target[r] - assigned[r] for r in RESOURCES}
            r = _pick(deficit, set(cost), i)
            cost[r] = 1
            assigned[r] += 1
        result.append(
            ProjectCard(
                id=f"grand-{card.id}",
                name=f"Grand {card.name}",
                category=card.category,
                cost=cost,
                effect=card.effect,
                vp=1,
            )
        )
    return tuple(result)


@lru_cache(maxsize=None)
def build_catalog(split: str) -> tuple[tuple[ProjectCard, ...], tuple[ProjectCard, ...], tuple[ProjectCard, ...]]:
    """(city, market, prestige) cards for a resource split from ``RESOURCE_SPLITS``."""
    if split not in RESOURCE_SPLITS:
        raise ValueError(f"Unknown resource split {split!r}; options: {', '.join(RESOURCE_SPLITS)}")
    shares = RESOURCE_SPLITS[split]
    if shares is None:
        return _HANDWRITTEN_CITY, MARKET_PROJECTS, _HANDWRITTEN_PRESTIGE
    plain = _fill(_BASE_CITY_PROJECTS + _SMALL_STORAGE, shares["city"])
    has_grand = [c for c in plain if not c.id.startswith("small-")]
    city = plain + _grand_from(tuple(has_grand), shares["grand"])
    prestige = tuple(
        card
        for tier in ("small", "medium", "major")
        for card in _fill(tuple(c for c in _HANDWRITTEN_PRESTIGE if c.tier == tier), shares[tier])
    )
    return city, MARKET_PROJECTS, prestige


