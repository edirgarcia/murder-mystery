def _grand(card: ProjectCard) -> ProjectCard:
    """Same effect, a few more goods in new types, and a little prestige (no cash cost).

    Extra cost: 1 each of two resources the card doesn't use yet — so the VP
    comes from diversity, like Prestige projects.
    """
    main = max(card.cost, key=lambda r: card.cost[r])
    i = RESOURCES.index(main)
    extras = [r for r in (RESOURCES[(i + k) % len(RESOURCES)] for k in range(4, 8)) if r not in card.cost][:2]
    cost = dict(card.cost)
    for r in extras:
        cost[r] = 1
    return ProjectCard(
        id=f"grand-{card.id}",
        name=f"Grand {card.name}",
        category=card.category,
        cost=cost,
        effect=card.effect,
        vp=1,
    )


