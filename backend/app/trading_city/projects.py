# --- Market Projects: one card per resource x axis x direction (spec §30-§35, §40) ---

_MARKET_TEMPLATES: tuple[tuple[MarketAxis, MarketLevel, str, tuple[tuple[int, int], ...]], ...] = (
    # (axis, level, name suffix, ((resource offset, units), ...)) — offsets wrap around RESOURCES
    (MarketAxis.SUPPLY, MarketLevel.UP, "Subsidy", ((0, 1), (3, 1), (5, 1))),
    (MarketAxis.SUPPLY, MarketLevel.DOWN, "Embargo", ((2, 1), (4, 1), (6, 1))),
    (MarketAxis.DEMAND, MarketLevel.UP, "Craze", ((1, 2), (6, 1))),
    (MarketAxis.DEMAND, MarketLevel.DOWN, "Substitutes", ((3, 2), (7, 1))),
)


def _market_projects() -> tuple[ProjectCard, ...]:
    cards = []
    for i, resource in enumerate(RESOURCES):
        for axis, level, suffix, parts in _MARKET_TEMPLATES:
            cost = {RESOURCES[(i + off) % len(RESOURCES)]: n for off, n in parts}
            cards.append(
                ProjectCard(
                    id=f"{resource.value}-{axis.value}-{level.value}",
                    name=f"{resource.value.title()} {suffix}",
                    category=ProjectCategory.MARKET,
                    cost=cost,
                    effect=Effect(EffectKind.MARKET, resource=resource, axis=axis, level=level),
                )
            )
    return tuple(cards)


MARKET_PROJECTS: tuple[ProjectCard, ...] = _market_projects()


