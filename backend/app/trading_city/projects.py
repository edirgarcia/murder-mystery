"""Project cards and the draft project catalog (spec §23-§42).

The catalog (names, costs, effects, VP) is balance data and expected to change
during playtesting. Effects are a small closed set interpreted by the engine.

Costs are sized for the 5-unit economy (2/1/1/1 production, upkeep 3), where a
city has roughly 2 spare units per round — smaller than the spec's original
suggestions (§39-§41), which assumed 10-unit production:

- City: 3 units, 2 types (concentrated: rewards specialisation); Small storage 2 units
- Grand City: base + 2 units in 2 new types, 1 VP
- Market: 3 units, 2-3 types
- Prestige small 3 units / 2-3 types; medium 4-5 / 4-5; major 6-8 / 6-8.
  Diversity, not volume, is what makes the big ones hard.

The hand-written cards below define each card's *shape* (units per resource
type), effect and VP. Which resources fill those shapes is generated by
``build_catalog`` so that demand is spread evenly — optionally tilted so basic
goods dominate early cards and refined goods dominate late ones (see
``RESOURCE_SPLITS``). Names may no longer match their ingredients; balance wins.
"""

from __future__ import annotations

